//! Agent-triggered plan-step review (agent-settings 08 §5): its settings, the records a review
//! leaves on a step, the change set a step owns, and the runner contract the host tools call.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

use crate::{ModelRef, PlanItemId, PlanScope, Result, ThinkingLevel};

/// The 评审 group of 设置 → 模型. Both switches default to off, as in the original.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ReviewPrefs {
    /// `None`: the review follows the default chat model ("{name}（默认）").
    pub model: Option<ModelRef>,
    /// `None`: the default effort. Always passed explicitly so a reviewer never inherits the
    /// worker's effort.
    pub effort: Option<ThinkingLevel>,
    /// Agent 触发的评审: whether worker sessions get the `request_review` tool.
    pub agent_review: bool,
    /// 自动修复循环: whether `request_changes` sends the worker straight back to fix (one round).
    pub auto_fix: bool,
}

/// One of the two review switches.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReviewSwitch {
    AgentReview,
    AutoFix,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Verdict {
    Approve,
    RequestChanges,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FindingState {
    /// Given to the worker (to fix, or to report); `resolve_comment` may resolve it.
    Open,
    Resolved,
}

/// One reviewer finding. Unlike a review comment it may have no line (a file- or step-level
/// problem), so it lives with the review record, not in the comment list.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ReviewFinding {
    /// `rf_…`, generated by the host; the reviewer's own ids are not kept.
    pub id: String,
    pub path: Option<String>,
    pub start_line: Option<u32>,
    pub end_line: Option<u32>,
    pub body: String,
    pub state: FindingState,
}

/// The latest verdict on one step.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ReviewRecord {
    pub verdict: Verdict,
    pub summary: Option<String>,
    pub findings: Vec<ReviewFinding>,
    /// The watermark: the step's commits as they were when this review started.
    pub reviewed_shas: Vec<String>,
    pub model: Option<ModelRef>,
    /// Unix milliseconds.
    pub at: u64,
}

/// What a step changed: commits the host made or adopted for it, or paths it could not commit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum ItemChange {
    Commit { sha: String, label: String },
    Path { path: String },
}

/// A step's work window, opened when it goes `InProgress` (08 §5.8).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Baseline {
    /// Uncommitted paths at the start; work on them cannot be told apart from the step's.
    pub paths: Vec<String>,
    pub head: Option<String>,
    /// Another chat had a window open in the same worktree; sticky once set.
    pub shared: bool,
}

/// One chat's review state beside its plan, in the same store and lock.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct StepReviews {
    pub verdicts: BTreeMap<PlanItemId, ReviewRecord>,
    /// Steps under review, with their commits when the review started.
    pub pending: BTreeMap<PlanItemId, Vec<String>>,
    /// Automatic fix rounds spent: 1 = the worker was sent to fix, 2 = the user decides. Kept
    /// apart from `verdicts` so dropping a record never grants another round.
    pub auto_cycles: BTreeMap<PlanItemId, u8>,
    pub baselines: BTreeMap<PlanItemId, Baseline>,
}

/// Who started a review.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReviewOrigin {
    /// The worker's `request_review` call. `waits`: the call blocks for the verdict (pi, OMP);
    /// otherwise the verdict comes back as a later message (DSH, 08 §5.5).
    Tool { waits: bool },
    /// The user's 检查 button.
    Button,
    /// The host, after a fix round landed.
    AutoReReview,
}

/// A review [`ReviewRunner::start`] began or joined.
#[derive(Debug, Clone)]
pub struct StartedReview {
    pub handle: ReviewHandle,
    /// The step was already under review; this call joined it.
    pub joined: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReviewOutcome {
    Approved,
    /// The reviewer approved, but earlier findings on the step are still unresolved.
    ApproveBlocked {
        open: usize,
    },
    /// Sent back to fix (one automatic round).
    ChangesFix,
    /// Auto-fix off or spent: the worker reports, the user decides.
    ChangesStop,
    Failed {
        message: String,
    },
}

/// A finished review: what happened and the text for the worker (tool result or message).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReviewResult {
    pub outcome: ReviewOutcome,
    pub record: Option<ReviewRecord>,
    pub text: String,
}

/// Starts and cancels plan-step reviews; implemented by the app, called by the host tools and
/// the UI. Blocking calls run on background threads.
pub trait ReviewRunner: Send + Sync {
    /// Starts a review of `item`, or joins the one already running for it. Returns at once.
    fn start(
        &self,
        scope: &PlanScope,
        item: &PlanItemId,
        origin: ReviewOrigin,
    ) -> Result<StartedReview>;

    /// Cancels the chat's running review, if any; it finishes as `Failed`.
    fn cancel(&self, scope: &PlanScope);
}

/// UI-visible review completion. Synchronous tool callers consume the same `ReviewResult` from the
/// handle; DSH, button and automatic re-review paths consume this event.
#[derive(Debug, Clone)]
pub enum ReviewEvent {
    Started {
        scope: PlanScope,
        item: PlanItemId,
    },
    Finished {
        scope: PlanScope,
        item: PlanItemId,
        result: ReviewResult,
    },
}

type DoneCallback = Box<dyn FnOnce(&ReviewResult) + Send>;

#[derive(Default)]
struct HandleState {
    result: Option<ReviewResult>,
    callbacks: Vec<DoneCallback>,
}

/// One running review. Clones share the result; [`ReviewHandle::wait`] blocks until it is set.
#[derive(Clone, Default)]
pub struct ReviewHandle {
    inner: std::sync::Arc<(std::sync::Mutex<HandleState>, std::sync::Condvar)>,
}

impl std::fmt::Debug for ReviewHandle {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ReviewHandle").finish_non_exhaustive()
    }
}

impl ReviewHandle {
    /// Sets the result once and runs the callbacks registered so far; later calls are ignored.
    pub fn finish(&self, result: ReviewResult) {
        let callbacks = {
            let mut state = self.lock();
            if state.result.is_some() {
                return;
            }
            state.result = Some(result.clone());
            std::mem::take(&mut state.callbacks)
        };
        self.inner.1.notify_all();
        for callback in callbacks {
            callback(&result);
        }
    }

    /// Blocks the calling thread until the review finishes.
    pub fn wait(&self) -> ReviewResult {
        let mut state = self.lock();
        loop {
            if let Some(result) = &state.result {
                return result.clone();
            }
            state = self
                .inner
                .1
                .wait(state)
                .unwrap_or_else(std::sync::PoisonError::into_inner);
        }
    }

    /// Runs `callback` when the review finishes (at once if it already has).
    pub fn on_done(&self, callback: impl FnOnce(&ReviewResult) + Send + 'static) {
        let done = {
            let mut state = self.lock();
            match &state.result {
                Some(result) => Some(result.clone()),
                None => {
                    state.callbacks.push(Box::new(callback));
                    return;
                }
            }
        };
        if let Some(result) = done {
            callback(&result);
        }
    }

    pub fn is_finished(&self) -> bool {
        self.lock().result.is_some()
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, HandleState> {
        self.inner
            .0
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }
}
